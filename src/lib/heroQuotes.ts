/** The quote for a given day — deterministic, stable within the day. */
export function heroQuoteForDate(date: Date = new Date()): string {
  const day = Math.floor(date.getTime() / 86_400_000);
  return HERO_QUOTES[((day % HERO_QUOTES.length) + HERO_QUOTES.length) % HERO_QUOTES.length];
}
